-- V1: 最初のテーブル定義(Flyway を入れる前に、Hibernate が自動で作っていた形をそのまま書いたもの)
--
-- ・すでにテーブルがある DB(開発用・本番)では、この V1 は流さず「V1 まで済み」として扱う
--   (application.properties の spring.flyway.baseline-on-migrate)
-- ・制約の名前(uk…・fk…)は、Hibernate が付けた名前のまま。どの DB でも同じ名前にして、
--   あとで制約を変える SQL が、どの DB にもそのまま使えるようにする
-- ・ログイン状態のテーブル(spring_session)は、Spring Session が自分で作るので、ここには書かない
--
-- テーブルを変えるときは、このファイルを書き換えず、V2__〜.sql を足すこと(一度流したファイルは変えない)

-- ユーザー
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    avatar_path character varying(255),
    bio character varying(160),
    created_at timestamp(6) with time zone NOT NULL,
    display_name character varying(50),
    email character varying(254) NOT NULL,
    email_verified boolean NOT NULL,
    failed_login_count integer NOT NULL,
    google_sub character varying(255),
    handle character varying(15),
    handle_lower character varying(15),
    header_path character varying(255),
    locked_until timestamp(6) with time zone,
    password_hash character varying(100),
    role character varying(10) NOT NULL,
    suspended boolean NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email),
    CONSTRAINT ukfla1a4b51hmn2n4kuw14u210i UNIQUE (google_sub),
    CONSTRAINT uknfkqit59m3w2riy5ijxbtjuqr UNIQUE (handle_lower),
    CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN'))
);

-- メールの確認・パスワードの再設定に使う、1 回だけのしるし(ハッシュで保存)
CREATE TABLE email_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    purpose character varying(20) NOT NULL,
    token_hash character varying(64) NOT NULL,
    used_at timestamp(6) with time zone,
    user_id bigint NOT NULL,
    CONSTRAINT email_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT uk2l5l8ipiwjlrfbba58bnwjbss UNIQUE (token_hash),
    CONSTRAINT fk9j2pq9xa8fh246k3uruj9feec FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT email_tokens_purpose_check CHECK (purpose IN ('VERIFY_EMAIL', 'RESET_PASSWORD'))
);

-- 投稿(返信は reply_to_id。元の投稿が消えても返信は残すので、外部キーは付けない)
CREATE TABLE posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone NOT NULL,
    deleted_at timestamp(6) with time zone,
    edited_at timestamp(6) with time zone,
    hidden boolean NOT NULL,
    reply_to_id bigint,
    text character varying(4000) NOT NULL,
    author_id bigint NOT NULL,
    CONSTRAINT posts_pkey PRIMARY KEY (id),
    CONSTRAINT fk6xvn0811tkyo3nfjk2xvqx6ns FOREIGN KEY (author_id) REFERENCES users (id)
);
CREATE INDEX idx_posts_author ON posts (author_id, id);
CREATE INDEX idx_posts_reply_to ON posts (reply_to_id, id);
CREATE INDEX idx_posts_created_at ON posts (created_at);

